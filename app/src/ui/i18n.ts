/** Русское склонение: 1 кость, 2 кости, 5 костей. */
function ruTiles(n: number): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return `${n} кость`;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return `${n} кости`;
  return `${n} костей`;
}

