/** Українська відміна: 1 кістка, 2 кістки, 5 кісток. */
function ukTiles(n: number): string {
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return `${n} кістка`;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return `${n} кістки`;
  return `${n} кісток`;
}

